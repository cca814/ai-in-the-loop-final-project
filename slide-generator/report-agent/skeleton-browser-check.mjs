// Walking skeleton: no conversation UI or revision requests; real Slidev Markdown route.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
import { openTestWorkspace } from './browser-fixture.mjs';
const { chromium } = createRequire(import.meta.url)('../slide-export/node_modules/playwright-chromium');
const browser = await chromium.launch({ headless: true });
const original = '# 近期成果\n\n- 報告編輯器已提供預覽。\n\n## Speaker Notes\n\n說明目前可用的報告預覽。';
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('dialog', dialog => dialog.accept());
  let revisionRequests = 0, delay = false;
  page.on('request', request => { if (request.url().includes('/api/reports/revise')) revisionRequests++; });
  await page.route('**/api/reports/generate', async route => {
    if (delay) await new Promise(resolve => setTimeout(resolve, 600));
    try { await route.fulfill({ json: { report: original } }); } catch { /* Request was cancelled. */ }
  });
  await openTestWorkspace(page, process.env.REPORT_TEST_URL || 'http://localhost:3000');
  assert.equal(await page.getByRole('heading', { name: '對話修改', exact: true }).count(), 0);
  assert.equal(await page.getByLabel('修改要求', { exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: '預覽修改', exact: true }).count(), 0);
  assert.equal(await page.getByRole('dialog').count(), 0);
  assert.equal(await page.getByRole('button', { name: '下載報告與審閱紀錄', exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: '檢查目前草稿', exact: true }).count(), 0);
  assert.equal(await page.getByText(/^品質檢查：/).count(), 0);
  assert.equal(await page.locator('button').filter({ hasText: /^(儲存草稿|儲存草稿與對話|載入已存草稿)$/ }).count(), 0);
  assert.match(await page.getByLabel('報告生成需求（選填）').inputValue(), /先說明整份專案.*近期成果與待處理問題/);
  await page.getByRole('button', { name: '生成報告', exact: true }).click();
  const editor = page.getByLabel('直接編輯 Markdown', { exact: true });
  await page.waitForFunction(() => document.querySelector('#report-markdown')?.value.includes('近期成果'));
  const inspection = page.getByRole('status', { name: '報告自動檢查提醒', exact: true });
  await inspection.getByText(/此頁未顯示來源/).waitFor();
  const manual = original.replace('說明目前可用的報告預覽。', '這是手動編輯後的講稿。');
  await editor.fill(manual);
  await page.getByRole('button', { name: '復原上一版', exact: true }).click(); assert.equal(await editor.inputValue(), original);
  await page.getByRole('button', { name: '恢復剛才的修改', exact: true }).click(); assert.equal(await editor.inputValue(), manual);
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '下載 Markdown', exact: true }).click();
  assert.equal(await readFile(await (await download).path(), 'utf8'), manual);
  await editor.fill(`${manual}\n\n## Sources\n\n- [Source](https://example.com/source)`);
  assert.equal(await inspection.count(), 0); // No summary or success badge when no rule warns.
  await editor.fill(manual);
  await editor.fill('# 缺少講稿\n\n- 手動編輯');
  await inspection.getByText(/講稿區塊/).waitFor();
  await page.getByRole('button', { name: '復原上一版', exact: true }).click();
  assert.equal(await editor.inputValue(), manual);
  assert.equal(await inspection.getByText(/講稿區塊/).count(), 0);
  await page.getByRole('button', { name: '恢復剛才的修改', exact: true }).click();
  await inspection.getByText(/講稿區塊/).waitFor();
  await editor.fill(manual);
  const layout = await page.locator('.reports-grid').evaluate(element => ({ columns: getComputedStyle(element).gridTemplateColumns.split(' ').length }));
  assert.equal(layout.columns, 2);
  await page.setViewportSize({ width: 390, height: 1000 });
  const mobile = await page.locator('.reports-grid').evaluate(element => getComputedStyle(element).gridTemplateColumns.split(' ').length);
  assert.equal(mobile, 1);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByLabel('網頁播放轉場').selectOption('');
  await page.getByLabel('我已確認目前報告內容').check();
  await page.getByRole('button', { name: '產生 Slidev 原稿', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#slides-markdown')?.value.includes('手動編輯後的講稿'));
  assert.equal(await editor.inputValue(), manual);
  await page.locator('.reports-slidePreview > summary').click();
  const slideEditor = page.getByLabel('編輯 slides.md', { exact: true });
  const editedSlides = (await slideEditor.inputValue()).replace('手動編輯後的講稿', '直接修改 slides 的講稿');
  await slideEditor.fill(editedSlides);
  assert.equal(await editor.inputValue(), manual);
  const slidesDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: '下載 slides.md', exact: true }).click();
  assert.equal(await readFile(await (await slidesDownload).path(), 'utf8'), editedSlides);
  await editor.fill(`${manual}\n`);
  assert.equal(await page.getByRole('button', { name: '建立網頁簡報', exact: true }).isDisabled(), true);
  delay = true;
  await page.getByRole('button', { name: '重新生成報告', exact: true }).click();
  await page.getByRole('button', { name: '取消目前操作', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '操作已取消' }).waitFor();
  await page.waitForTimeout(800);
  assert.equal(await editor.inputValue(), `${manual}\n`);
  assert.equal(revisionRequests, 0);
  console.log('PASS: no conversation UI/requests, two-column desktop/single-column mobile, generate/manual edit/undo/download, real slides.md generation, stale export guard and cancelled-generation preservation.');
} finally { await browser.close(); }
